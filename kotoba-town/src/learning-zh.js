export function actionChinese(verb,word){
 const noun=word.zh||word.jp;
 const verbs={'食べる':'吃','飲む':'喝','焼く':'烤','読む':'阅读','着る':'穿','はく':'穿','かぶる':'戴','開ける':'打开','閉める':'关上','鳴らす':'摇响'};
 return verbs[verb]?verbs[verb]+noun:'';
}
export function actionGrammarChinese(a){
 const byType={sit:'「に」表示坐的位置。',stand:'从坐着的状态站起来。',board:'「に」表示乘坐的交通工具。',alight:'这里的「を」表示离开的交通工具。',enter:'「に」表示进入的地方。',leave:'这里的「を」表示离开的地方。','light-on':'「電気をつける」表示开灯。','light-off':'「電気を消す」表示关灯。',wash:'「を」标记清洗的对象；「手」读作「て」。',sweep:'「床」读作「ゆか」，「を」标记清扫的对象。'};
 if(a.particle==='で') return '「で」标记使用的工具，「を」标记动作的对象。动词原形：'+a.verb+'。';
 return (byType[a.type]||'「を」标记动作的对象。')+' 动词原形：'+a.verb+'。';
}
